class Vehicle:
    """
    Базовый класс для транспортных средств.
    """

    def __init__(self, brand: str, model: str, year: int) -> None:
        """
        Инициализирует транспортное средство с маркой, моделью и годом выпуска.

        :param brand: Марка транспортного средства.
        :param model: Модель транспортного средства.
        :param year: Год выпуска транспортного средства.
        """
        self.__brand = brand  # Приватный атрибут, чтобы защитить марку от изменения извне.
        self.__model = model  # Приватный атрибут, чтобы защитить модель от изменения извне.
        self.__year = year    # Приватный атрибут, чтобы защитить год выпуска от изменения извне.

    def __str__(self) -> str:
        """Возвращает строковое представление транспортного средства."""
        return f"{self.__year} {self.__brand} {self.__model}"

    def __repr__(self) -> str:
        """Возвращает формальное строковое представление транспортного средства."""
        return f"Vehicle(brand='{self.__brand}', model='{self.__model}', year={self.__year})"

    def start_engine(self) -> str:
        """
        Запускает двигатель транспортного средства.

        :return: Сообщение о запуске двигателя.
        """
        return f"{self.__brand} {self.__model} запускает двигатель."


class Car(Vehicle):
    """
    Класс для легковых автомобилей, унаследованный от базового класса Vehicle.
    """

    def __init__(self, brand: str, model: str, year: int, doors: int) -> None:
        """
        Инициализирует легковой автомобиль с маркой, моделью, годом выпуска и количеством дверей.

        :param brand: Марка легкового автомобиля.
        :param model: Модель легкового автомобиля.
        :param year: Год выпуска легкового автомобиля.
        :param doors: Количество дверей в легковом автомобиле.
        """
        super().__init__(brand, model, year)
        self.doors = doors  # Публичный атрибут, так как может быть полезен для внешнего использования.

    def __str__(self) -> str:
        """Возвращает строковое представление легкового автомобиля с указанием количества дверей."""
        return f"{super().__str__()} (Двери: {self.doors})"

    def __repr__(self) -> str:
        """Возвращает формальное строковое представление легкового автомобиля."""
        return f"Car(brand='{self._Vehicle__brand}', model='{self._Vehicle__model}', year={self._Vehicle__year}, doors={self.doors})"

    def start_engine(self) -> str:
        """
        Запускает двигатель легкового автомобиля.

        Переопределяет метод родительского класса для добавления специфичного сообщения
        о запуске двигателя легкового автомобиля.

        :return: Сообщение о запуске двигателя легкового автомобиля.
        """
        return f"{super().start_engine()} (Легковой автомобиль)"


